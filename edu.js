/* Education features (Oct 14): Kids Planet Map (#km), Lesson Plan Builder (#lb), Satellite Explorer (#sx).
   Data: assets/data/edu.<lang>.json, generated by scripts/build-edu.py from the site's own pages. */
(function () {
  var lang = (document.documentElement.lang || 'en').slice(0, 2);
  var root = lang === 'en' ? '' : '../';
  var esc = function (s) { return String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;'); };
  var fmt = function (s, o) { return String(s).replace(/\{(\w+)\}/g, function (_, k) { return o[k] != null ? o[k] : ''; }); };
  var D = null;
  function load(cb) {
    if (D) return cb(D);
    fetch(root + 'assets/data/edu.' + lang + '.json?v=20261014f').then(function (r) { return r.json(); }).then(function (d) { D = d; cb(d); })
      .catch(function () { var e = document.querySelector('.edu-error'); if (e) e.hidden = false; });
  }
  /* ---------------- Kids map ---------------- */
  var km = document.getElementById('km');
  if (km) load(function (d) {
    var U = d.ui, panel = document.getElementById('km-panel'), btns = [].slice.call(km.querySelectorAll('[data-hub]')), factIdx = {};
    function show(hub, focus) {
      var h = d.hubs[hub]; if (!h) return;
      btns.forEach(function (b) { b.setAttribute('aria-pressed', b.dataset.hub === hub ? 'true' : 'false'); });
      var i = factIdx[hub] = ((factIdx[hub] == null ? -1 : factIdx[hub]) + 1) % Math.max(1, h.facts.length), f = h.facts[i];
      var sols = h.sols.slice(0, 6).map(function (s) {
        return '<li><a href="' + esc(s.u) + '"><img src="' + esc(s.img) + '" alt="" loading="lazy" width="300" height="225"><span>' + esc(s.t) + '</span></a></li>';
      }).join('');
      panel.innerHTML = '<h2 id="km-h" tabindex="-1"><span class="em" aria-hidden="true">' + h.emoji + '</span>' + esc(h.name) + '</h2>' +
        '<p class="edu-lead">' + esc(h.blurb) + '</p>' +
        (f ? '<div class="km-wow glass" data-tint="' + h.glass + '"><b>' + esc(U.wow) + '</b><p>' + esc(f.x) + '</p><p class="lb-small" style="color:#fff">' + esc(U.source) + ' <a href="' + esc(f.src) + '" rel="noopener" target="_blank">' + esc(f.sn) + '</a></p></div>' : '') +
        (h.facts.length > 1 ? '<p><button type="button" class="edu-bubble glass" data-tint="' + h.glass + '" id="km-more"><span class="em" aria-hidden="true">✨</span>' + esc(U.another) + '</button></p>' : '') +
        '<h3>' + esc(U.explore) + '</h3><ul class="km-sols">' + sols + '</ul>' +
        '<p><a class="edu-bubble glass" data-tint="' + h.glass + '" href="' + esc(h.url) + '">' + esc(fmt(U.seeall, { n: h.sols.length, hub: h.name })) + '</a> ' +
        '<button type="button" class="edu-bubble glass" id="km-back"><span class="em" aria-hidden="true">🗺️</span>' + esc(U.back) + '</button></p>';
      panel.hidden = false;
      var more = document.getElementById('km-more'); if (more) more.onclick = function () { show(hub, false); document.getElementById('km-more').focus(); };
      document.getElementById('km-back').onclick = function () { var b = km.querySelector('[data-hub="' + hub + '"]'); km.scrollIntoView({ block: 'start' }); b && b.focus(); };
      if (focus) { var hh = document.getElementById('km-h'); hh.focus({ preventScroll: true }); panel.scrollIntoView({ behavior: matchMedia('(prefers-reduced-motion: reduce)').matches ? 'auto' : 'smooth', block: 'start' }); }
    }
    btns.forEach(function (b) { b.addEventListener('click', function () { factIdx[b.dataset.hub] = factIdx[b.dataset.hub] == null ? Math.floor(Math.random() * 50) - 1 : factIdx[b.dataset.hub]; show(b.dataset.hub, true); }); });
    var sp = document.getElementById('km-surprise');
    if (sp) sp.addEventListener('click', function () { var b = btns[Math.floor(Math.random() * btns.length)]; b.click(); });
  });
  /* ---------------- Lesson builder ---------------- */
  var lb = document.getElementById('lb');
  if (lb) load(function (d) {
    var U = d.ui, L = d.lesson, out = document.getElementById('lb-plan');
    var q = new URLSearchParams(location.search);
    ['band', 'hub', 'min'].forEach(function (k) { var v = q.get(k), el = lb.elements[k]; if (v && el && [].some.call(el.options, function (o) { return o.value === v; })) el.value = v; });
    function pick(arr, n, seed) { var a = arr.slice(), r = []; seed = seed || 1; while (a.length && r.length < n) { seed = (seed * 9301 + 49297) % 233280; r.push(a.splice(Math.floor(seed / 233280 * a.length), 1)[0]); } return r; }
    function build(e) {
      if (e) e.preventDefault();
      var band = lb.elements.band.value, hub = lb.elements.hub.value, min = +lb.elements.min.value, B = L.bands[band], h = d.hubs[hub];
      var seed = (new Date().getDate() * 31 + min) % 997 + 1;
      var nS = B.sols + (min >= 90 ? 1 : 0), nF = B.facts + (min >= 60 ? 1 : 0);
      var sols = pick(h.sols, nS, seed), facts = pick(h.facts, nF, seed + 7), terms = h.terms.slice(0, B.terms);
      var T = { hub: h.name, sol: sols[0] ? sols[0].t : h.name };
      var tm = [0.15, 0.3, 0.4, 0.15].map(function (p) { return Math.max(5, Math.round(min * p / 5) * 5); });
      tm[2] = Math.max(5, min - tm[0] - tm[1] - tm[3]);
      var solLinks = sols.map(function (s) { return '<a href="' + esc(s.u) + '">' + esc(s.t) + '</a>'; }).join(', ');
      var html = '<h2>' + esc(fmt(L.title, T)) + '</h2><p class="lb-meta">' + esc(B.label) + ' · ' + esc(fmt(L.minutes, { n: min })) + '</p>' +
        '<p>' + esc(h.blurb) + '</p>' +
        '<h3>' + esc(L.h.objectives) + '</h3><ul>' + B.objectives.map(function (o) { return '<li>' + esc(fmt(o, T)) + '</li>'; }).join('') + '</ul>' +
        '<h3>' + esc(L.h.materials) + '</h3><ul>' + B.materials.map(function (o) { return '<li>' + esc(o) + '</li>'; }).join('') +
          '<li><a href="' + root + (lang === 'en' ? '' : lang + '/') + 'Teachers.html">' + esc(L.sheets) + '</a></li></ul>' +
        '<h3>' + esc(L.h.sequence) + '</h3><ol>' +
          '<li><b>' + esc(fmt(L.step.hook, { n: tm[0] })) + '</b> ' + esc(L.step.hookText) + '</li>' +
          '<li><b>' + esc(fmt(L.step.explore, { n: tm[1] })) + '</b> ' + esc(L.step.exploreText) + ' ' + solLinks + '.</li>' +
          '<li><b>' + esc(fmt(L.step.activity, { n: tm[2] })) + '</b> ' + esc(fmt(B.activity, T)) + '</li>' +
          '<li><b>' + esc(fmt(L.step.wrap, { n: tm[3] })) + '</b> ' + esc(L.step.wrapText) + '</li></ol>' +
        (facts.length ? '<h3>' + esc(L.h.facts) + '</h3>' + facts.map(function (f) { return '<p class="lb-fact">' + esc(f.x) + ' <span class="lb-small">(' + esc(U.source) + ' <a href="' + esc(f.src) + '">' + esc(f.sn) + '</a>)</span></p>'; }).join('') : '') +
        '<h3>' + esc(L.h.solutions) + '</h3><ul>' + sols.map(function (s) { return '<li><a href="' + esc(s.u) + '">' + esc(s.t) + '</a>: ' + esc(s.d) + '</li>'; }).join('') + '</ul>' +
        (terms.length ? '<h3>' + esc(L.h.vocab) + '</h3><ul>' + terms.map(function (t) { return '<li><b><a href="' + esc(t.u) + '">' + esc(t.t) + '</a></b>: ' + esc(t.d) + '</li>'; }).join('') + '</ul>' : '') +
        '<h3>' + esc(L.h.questions) + '</h3><ol>' + L.questions.map(function (x, i) { return '<li>' + esc(fmt(x, { sol: (sols[i % Math.max(1, sols.length)] || {}).t || h.name, hub: h.name })) + '</li>'; }).join('') + '</ol>' +
        '<h3>' + esc(L.h.exit) + '</h3><p>' + esc(fmt(B.exit, T)) + '</p>' +
        '<h3>' + esc(L.h.sources) + '</h3><ul class="lb-small">' +
          sols.map(function (s) { return '<li>Saving Planets. (n.d.). ' + esc(s.t) + '. ' + esc(s.abs) + '</li>'; }).join('') +
          facts.map(function (f) { return '<li>' + esc(f.sn) + '. ' + esc(f.src) + '</li>'; }).join('') + '</ul>' +
        '<p class="lb-small">' + esc(L.footer) + '</p>';
      out.innerHTML = html; out.hidden = false;
      document.getElementById('lb-print').hidden = false;
      var u = new URL(location.href); u.searchParams.set('band', band); u.searchParams.set('hub', hub); u.searchParams.set('min', min); history.replaceState(null, '', u);
      if (e) { out.setAttribute('tabindex', '-1'); out.focus(); }
    }
    lb.addEventListener('submit', build);
    document.getElementById('lb-print').addEventListener('click', function () { window.print(); });
    if (q.get('hub')) build();
  });
  /* ---------------- Satellite explorer ---------------- */
  var sx = document.getElementById('sx');
  if (sx) {
    var stage = sx.querySelector('.sx-stage'), status = document.getElementById('sx-status'), parts = [].slice.call(sx.querySelectorAll('.sx-part')),
      slots = [].slice.call(sx.querySelectorAll('.sx-slot')), sel = null, msg = {};
    [].forEach.call(sx.querySelectorAll('[data-msg]'), function (m) { msg[m.dataset.msg] = m.textContent.trim(); });
    slots.forEach(function (s) { s._empty = s.textContent.trim(); s._label = s.getAttribute('aria-label') || ''; });
    var lvlBox = document.getElementById('sx-body');
    [].forEach.call(document.querySelectorAll('input[name="sx-level"]'), function (r) {
      r.addEventListener('change', function () { lvlBox.className = 'lvl-' + r.value; });
    });
    function say(t) { status.textContent = t; }
    function place(p, s) {
      if (s.dataset.part !== p.dataset.part) { s.classList.remove('sx-shake'); void s.offsetWidth; s.classList.add('sx-shake'); say(msg.wrong || 'Try another spot!'); return false; }
      s.classList.add('done', 'glass'); s.dataset.tint = p.dataset.tint || 'space';
      s.innerHTML = '<span class="em" aria-hidden="true">' + p.dataset.em + '</span>' + esc(p.dataset.name);
      s.setAttribute('aria-label', p.dataset.name + ' ✓');
      p.classList.add('used'); p.setAttribute('aria-pressed', 'false'); sel = null;
      [].forEach.call(document.querySelectorAll('.sx-card'), function (c) { c.classList.remove('current'); });
      var card = document.getElementById('part-' + p.dataset.part); if (card) { card.classList.remove('locked'); card.classList.add('current'); }
      var left = slots.filter(function (x) { return !x.classList.contains('done'); }).length;
      say(left ? (msg.right || 'Nice!') + ' ' + p.dataset.name + ' ✓' : (msg.done || 'You built a satellite!'));
      return true;
    }
    function select(p) { if (p.classList.contains('used')) return; sel = p; parts.forEach(function (x) { x.setAttribute('aria-pressed', x === p ? 'true' : 'false'); }); say((msg.pick || 'Now tap its spot on the satellite:') + ' ' + p.dataset.name); }
    slots.forEach(function (s) { s.addEventListener('click', function () { if (sel) place(sel, s); else say(msg.first || 'Pick a part first.'); }); });
    parts.forEach(function (p) {
      var start = null, ghost = null, moved = false;
      p.addEventListener('pointerdown', function (e) {
        if (p.classList.contains('used') || (e.pointerType === 'mouse' && e.button !== 0)) return;
        start = { x: e.clientX, y: e.clientY, id: e.pointerId }; moved = false;
        try { p.setPointerCapture(e.pointerId); } catch (_) {}
      });
      p.addEventListener('pointermove', function (e) {
        if (!start || e.pointerId !== start.id) return;
        if (!moved && Math.hypot(e.clientX - start.x, e.clientY - start.y) > 8) {
          moved = true; ghost = p.cloneNode(true); ghost.classList.add('sx-ghost'); ghost.removeAttribute('id'); ghost.setAttribute('aria-hidden', 'true'); ghost.style.width = p.offsetWidth + 'px'; document.body.appendChild(ghost);
        }
        if (moved) {
          e.preventDefault(); ghost.style.left = e.clientX + 'px'; ghost.style.top = e.clientY + 'px';
          var t = document.elementFromPoint(e.clientX, e.clientY), s = t && t.closest && t.closest('.sx-slot');
          slots.forEach(function (x) { x.classList.toggle('hot', x === s && !x.classList.contains('done')); });
        }
      });
      function end(e) {
        if (!start) return;
        var wasMoved = moved; start = null; moved = false;
        if (ghost) { ghost.remove(); ghost = null; }
        slots.forEach(function (x) { x.classList.remove('hot'); });
        if (wasMoved) {
          p.dataset.dragged = '1';
          var t = document.elementFromPoint(e.clientX, e.clientY), s = t && t.closest && t.closest('.sx-slot');
          if (s && !s.classList.contains('done')) place(p, s); else say(msg.drop || 'Drop it on a dashed spot.');
        }
      }
      p.addEventListener('pointerup', end); p.addEventListener('pointercancel', function () { start = null; moved = false; if (ghost) { ghost.remove(); ghost = null; } });
      p.addEventListener('click', function () { if (p.dataset.dragged) { delete p.dataset.dragged; return; } select(p); });
    });
    var auto = document.getElementById('sx-auto'), reset = document.getElementById('sx-reset');
    if (auto) auto.addEventListener('click', function () { parts.forEach(function (p) { if (!p.classList.contains('used')) { var s = slots.filter(function (x) { return x.dataset.part === p.dataset.part; })[0]; s && place(p, s); } }); });
    if (reset) reset.addEventListener('click', function () {
      slots.forEach(function (s) { s.classList.remove('done', 'glass'); s.textContent = s._empty; s.setAttribute('aria-label', s._label); });
      parts.forEach(function (p) { p.classList.remove('used'); p.setAttribute('aria-pressed', 'false'); });
      [].forEach.call(document.querySelectorAll('.sx-card'), function (c) { c.classList.add('locked'); c.classList.remove('current'); });
      sel = null; say(msg.reset || '');
    });
    [].forEach.call(document.querySelectorAll('.sx-card'), function (c) { c.classList.add('locked'); });
  }
})();
