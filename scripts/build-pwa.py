PWA = re.compile(r'<!-- PWA:START -->.*?<!-- PWA:END -->\n?', re.S)
PWAJ = re.compile(r'<!-- PWA-JS:START -->.*?<!-- PWA-JS:END -->', re.S)
HEAD = ('<!-- PWA:START --><link rel="manifest" href="/manifest.webmanifest"><meta name="theme-color" content="%s">'
        '<meta name="mobile-web-app-capable" content="yes"><meta name="apple-mobile-web-app-capable" content="yes">'
        '<meta name="apple-mobile-web-app-title" content="Saving Planets"><meta name="apple-mobile-web-app-status-bar-style" content="black-translucent"><!-- PWA:END -->\n' % THEME)
JS = '<!-- PWA-JS:START --><script src="/pwa.js?v=%s" defer></script><!-- PWA-JS:END -->' % VER

def inject(p):
    s = p.read_text(encoding='utf-8'); o = s
    if '</head>' not in s or '</body>' not in s: return 0
    s = PWA.sub('', s); s = PWAJ.sub('', s)
    if 'name="theme-color"' in s: s = s.replace('<meta name="theme-color" content="%s">' % THEME, '', 1)
    s = s.replace('</head>', HEAD + '</head>', 1)
    i = s.find('<!-- CF-WA:START -->'); j = s.rfind('</body>')
    s = s[:i] + JS + s[i:] if 0 <= i < j else s[:j] + JS + s[j:]
    if s != o: p.write_text(s, encoding='utf-8'); return 1
    return 0

def main():
    icons()
    (ROOT / 'manifest.webmanifest').write_text(json.dumps(MANIFEST, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    (ROOT / 'sw.js').write_text(SW.replace('__VER__', VER), encoding='utf-8')
    (ROOT / 'pwa.js').write_text(PWAJS.replace('__T__', json.dumps({k: list(v) for k, v in T.items()}, ensure_ascii=False)), encoding='utf-8')
    (ROOT / 'offline.html').write_text(offline(), encoding='utf-8')
    n = 0
    for d in [ROOT] + [ROOT / l for l in LANGS]:
        for p in sorted(d.glob('*.html')):
            if p.name in SKIP or p.name == 'offline.html': continue
            n += inject(p)
    print(f'build-pwa: {n} pages updated')

if __name__ == '__main__': main()
