def mark(size, maskable):
    s = 4; n = size * s
    im = Image.new('RGBA', (n, n), BG + (255,) if maskable else (0, 0, 0, 0)); d = ImageDraw.Draw(im)
    k = n / 32 * (0.72 if maskable else 1.0); o = (n - 32 * k) / 2   # maskable: keep mark inside the 80% safe zone
    c = lambda cx, cy, r, f: d.ellipse([o + (cx - r) * k, o + (cy - r) * k, o + (cx + r) * k, o + (cy + r) * k], fill=f)
    c(16, 16, 15, BG + (255,)); c(12, 14, 6, GREEN + (255,)); c(20, 18, 4, TEAL + (255,))
    return im.resize((size, size), Image.LANCZOS)

